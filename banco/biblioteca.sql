BEGIN;

CREATE TABLE usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL CHECK (length(trim(nome)) > 0),
    email VARCHAR(150) NOT NULL UNIQUE CHECK (email = lower(email)),
    senha VARCHAR(255) NOT NULL
);

CREATE TABLE livro (
    id_livro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL CHECK (length(trim(titulo)) > 0),
    autor VARCHAR(120) NOT NULL CHECK (length(trim(autor)) > 0),
    categoria VARCHAR(60) NOT NULL CHECK (length(trim(categoria)) > 0),
    quantidade INTEGER NOT NULL CHECK (quantidade >= 0)
);

CREATE TABLE emprestimo (
    id_emprestimo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_emprestimo DATE NOT NULL,
    data_prevista DATE NOT NULL,
    data_devolucao DATE,
    id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
    id_livro INTEGER NOT NULL REFERENCES livro(id_livro) ON DELETE RESTRICT,
    CHECK (data_prevista >= data_emprestimo),
    CHECK (data_devolucao IS NULL OR data_devolucao >= data_emprestimo)
);

CREATE INDEX idx_emprestimo_usuario ON emprestimo(id_usuario);
CREATE INDEX idx_emprestimo_livro ON emprestimo(id_livro);

